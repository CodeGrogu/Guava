package com.codegrogu.guava.model

// MechanicNote represents a single note written by a mechanic about the repair task.
// It keeps track of WHO wrote the note, WHAT they wrote, and WHEN they wrote it.
data class MechanicNote(
    // The actual note text that the mechanic typed (e.g., "Replaced tire successfully")
    val text: String,

    // The ID of the mechanic who wrote this note (for identification in Firestore)
    val mechanicUid: String,

    // The name of the mechanic who wrote this note (for display to other team members)
    val mechanicName: String,

    // The exact timestamp when this note was created (helps track order of updates)
    val timestamp: Long
)

// RepairTask represents a single repair job that needs to be done on a vehicle.
// Multiple mechanics can work on the same task, and they can leave notes and mark it complete.
data class RepairTask(
    // Unique identifier for this repair task (generated by Firestore)
    val id: String,

    // The description of what needs to be repaired (e.g., "Replace clutch", "Fix brake pads")
    val description: String,

    // Whether this repair task has been completed or not (true = done, false = still needs work)
    val isCompleted: Boolean,

    // The ID of the mechanic who marked this task as complete (empty string if not completed yet)
    val completedByUid: String,

    // The name of the mechanic who marked this task as complete (empty string if not completed yet)
    val completedByName: String,

    // The exact timestamp of when this task was marked as complete (null if not completed yet)
    val completedAt: Long?,

    // A list of all notes that mechanics have added about this task.
    // Each note includes who wrote it, what they wrote, and when they wrote it.
    // This creates an audit trail of mechanic work and communication.
    val notes: List<MechanicNote> = emptyList()
)

